import assert from 'node:assert/strict';
import { mkdtemp, cp, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import yaml from 'js-yaml';

const root = await mkdtemp(join(tmpdir(), 'bam-netlify-test-'));
try {
  for (const file of ['index.html','style.css','app.js','build.mjs','build-event.mjs','evenement.html','evenement.js','merci-evenement.html','admin','content','images','node_modules','package.json'])
    await cp(file, join(root, file), { recursive: true });
  const run = () => execFileSync(process.execPath, ['build.mjs'], { cwd: root, stdio: 'pipe' });
  const config = yaml.safeLoad(await readFile('admin/config.yml','utf8'));
  assert.equal(config.backend.name, 'git-gateway');
  assert.equal(config.collections[0].folder,'content/carte');
  run();
  let data = JSON.parse(await readFile(join(root,'dist/content/data.json'),'utf8'));
  assert.match(data.menu,/La carte se prépare/);
  await writeFile(join(root,'content/carte/salade.md'),`---\ntitle: 'Salade <img src=x onerror=alert(1)>'\nprice: 12.50\ncategorie: Entrée\n---\n**Fait maison**\n\n<script>alert(1)</script>\n`);
  await writeFile(join(root,'content/infos/horaires.md'),`---\ntelephone: '04 00 00 00 00'\nadresse: 'Une adresse de test'\nmidi: '12 h – 14 h'\nsoir: 'Fermé'\nalerte: |\n  Ligne une\n  Ligne deux\n---\n`);
  await writeFile(join(root,'content/rubriques/visible.md'),`---\ntitle: 'Nouvelle rubrique'\nordre: 2\nvisible: true\n---\nUn paragraphe.\n`);
  await writeFile(join(root,'content/rubriques/cachee.md'),`---\ntitle: 'Invisible'\nordre: 1\nvisible: false\n---\nMasquée.\n`);
  run();
  data = JSON.parse(await readFile(join(root,'dist/content/data.json'),'utf8'));
  const html=await readFile(join(root,'dist/index.html'),'utf8');
  assert.match(data.menu,/12,50/);assert.match(data.menu,/<strong>Fait maison<\/strong>/);
  assert.ok(!data.menu.includes('<script>'));assert.ok(!data.menu.includes('<img src=x'));
  assert.match(html,/12,50/);assert.match(html,/12 h – 14 h/);assert.match(data.infos,/tel:0400000000/);
  assert.match(data.alerte,/Ligne une\nLigne deux/);
  assert.match(data.rubriques,/Nouvelle rubrique/);assert.ok(!data.rubriques.includes('Invisible'));
  await writeFile(join(root,'content/carte/salade.md'),`---\ntitle: Salade\nprice: -1\ncategorie: Entrée\n---\nTest\n`);
  assert.throws(run);
  await rm(join(root,'content/carte/salade.md'));
  run();
  data = JSON.parse(await readFile(join(root,'dist/content/data.json'),'utf8'));
  assert.match(data.menu,/La carte se prépare/);
  assert.ok(!((await readFile(join(root,'dist/index.html'),'utf8')).includes('12,50')));
  assert.ok(!((await readFile('app.js','utf8')).includes('localStorage')));
  const eventSource = join(root,'content/evenement.md');
  const matter = (await import('gray-matter')).default;
  const eventData = matter(await readFile(eventSource,'utf8')).data;
  let eventHtml = await readFile(join(root,'dist/evenement/index.html'),'utf8');
  assert.equal((eventHtml.match(/class="event-menu"/g)||[]).length,3);
  assert.match(eventHtml,/href="tel:0486389998"/);
  assert.match(eventHtml,/mailto:maisonmartin2020@gmail.com/);
  assert.match(eventHtml,/data-netlify="true"/);
  assert.match(eventHtml,/name="form-name" value="reservation-evenement"/);
  assert.match(eventHtml,/netlify-honeypot="bot-field"/);
  assert.ok(eventHtml.includes('action="/merci-evenement/"'));
  for (const field of ['nom','email','telephone','convives','date','heure','formule','message'])
    assert.ok(eventHtml.includes(`name="${field}"`));
  eventData.title='Titre modifié <script>alert(1)</script>';
  eventData.menus[0].title='Menu été';eventData.menus[0].price=29.50;
  eventData.carte=[{title:'Entrée test',price:8.50,categorie:'Entrée',description:'Ligne 1\nLigne 2'},{title:'Plat test',price:15,categorie:'Plat'},{title:'Dessert test',price:6,categorie:'Dessert'}];
  await writeFile(eventSource,matter.stringify('',eventData));
  run();eventHtml=await readFile(join(root,'dist/evenement/index.html'),'utf8');
  assert.match(eventHtml,/29,50/);assert.match(eventHtml,/8,50/);
  assert.ok(eventHtml.includes('<option value="menu-1">Menu été</option>'));
  assert.ok(!eventHtml.includes('<script>alert(1)</script>'));
  assert.match(eventHtml,/Entrée test/);assert.match(eventHtml,/Plat test/);assert.match(eventHtml,/Dessert test/);
  eventData.menus.pop();await writeFile(eventSource,matter.stringify('',eventData));assert.throws(run);
  console.log('OK : Événement, trois menus, carte, tarifs, contact, options, échappement HTML et structure Netlify Forms.');
  console.log('OK : YAML Decap, carte vide, ajout/suppression, prix, Markdown sûr, horaires, alerte, rubriques visibles/masquées, HTML indexable.');
} finally { await rm(root,{recursive:true,force:true}); }
